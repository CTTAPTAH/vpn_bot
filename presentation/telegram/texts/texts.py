# Мои ключи
def txt_my_keys(all_keys: int, active_keys: int, keys: list[KeyDTO]) -> str:
    text = (
        "🔑 <b>Мои ключи</b>\n"
        f"Всего ключей: <b>{all_keys}</b>\n"
        f"Активных: <b>{active_keys}</b>\n\n"
    )

    if not keys:
        text += (
            "У вас пока нет ключей.\n"
            "Вы можете получить пробный доступ или выбрать тариф и купить доступ."
        )
        return text

    text += "<b>Ваши ключи:</b>\n"

    for i, key in enumerate(keys, start=1):
        status = "🔴" if key.is_expired else "🟢"
        date = key.end_at.strftime("%d.%m.%Y")

        text += f"{i}. {status} <b>{key.plan_name}</b> — до <b>{date}</b>\n"

    text += (
        "\nНажмите на ключ, чтобы:\n"
        "• посмотреть VLESS-ссылку\n"
        "• продлить доступ\n"
        "• удалить ключ\n\n"
        f"<b>Один ключ = VPN до {config.MAX_DEVICE_PER_KEY} устройств</b>"
    )

    return text

